import pytest
import numpy as np
import pandas as pd
from autonomous_engine.target_resolver import resolve_canonical_target_and_cost


def test_discrete_churn_target_resolution():
    """Text-based discrete churn targets must be mapped to binary adverse indicator (1=adverse)."""
    df = pd.DataFrame({
        "customer_id": [1, 2, 3, 4, 5],
        "churn": ["Yes", "No", "No", "Yes", "No"],
        "monthly_charges": [70.5, 25.0, 45.0, 89.0, 30.0]
    })
    res = resolve_canonical_target_and_cost(df)
    assert res["target_col"] == "churn"
    assert res["binary_target"].sum() == 2
    assert res["cost_col"] == "monthly_charges"
    assert res["is_financial"] is True


def test_5_star_rating_scale_adaptive_threshold():
    """5-star rating scales must NEVER classify 100% of rows as adverse failures."""
    np.random.seed(42)
    # Simulate e-commerce product ratings between 2.0 and 5.0
    ratings = [4.1, 4.3, 4.2, 4.0, 3.9, 4.4, 3.8, 4.5, 3.7, 3.5, 4.8, 5.0]
    df = pd.DataFrame({
        "product_id": range(len(ratings)),
        "rating": ratings,
        "price": [199.0, 399.0, 499.0, 150.0, 250.0, 1200.0, 350.0, 890.0, 420.0, 310.0, 1500.0, 2000.0]
    })
    res = resolve_canonical_target_and_cost(df)
    assert res["target_col"] == "rating"
    # Adverse events must be a subset (substandard ratings), NOT 100%
    assert 0 < res["binary_target"].sum() < len(ratings)
    assert res["cost_col"] == "price"


def test_synthetic_penalty_rejection():
    """Synthetic penalty columns generated by LLMs must NOT override physical monetary ledgers."""
    df = pd.DataFrame({
        "loan_id": [1, 2, 3, 4],
        "credit_amount": [5000.0, 12000.0, 3500.0, 8000.0],
        "synthetic_friction_penalty": [99999.0, 50000.0, 120000.0, 40000.0],
        "default": [0, 1, 0, 1]
    })
    res = resolve_canonical_target_and_cost(df)
    assert res["target_col"] == "default"
    assert res["cost_col"] == "credit_amount"
    assert res["cost_col"] != "synthetic_friction_penalty"
